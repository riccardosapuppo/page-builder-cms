// The icon box's icons, read from schema/icons.svg by the server's rules
// (build/site-icons.ts): the real file gives one icon for every name the
// schema allows, and a file breaking any rule stops the build, each rule
// shown with a fault planted in a copy of the file.
// @vitest-environment node
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { ICON_NAMES, SITE_OWN_ICONS } from "../src/shared/document.ts";
import { schemaDir } from "./paths.ts";
import { iconsFile, readIcons, siteIconsSource } from "./site-icons.ts";

const real = readFileSync(iconsFile, "utf8");

test("the sprite gives one icon for every name of the schema's enum, each with its viewBox and shapes", () => {
  const icons = readIcons(real);
  expect(Object.keys(icons).sort()).toEqual([...ICON_NAMES].sort());
  // The site's own eight, on their 40 grid, each with a shape in the accent.
  for (const name of SITE_OWN_ICONS) {
    const icon = icons[name]!;
    expect(icon.viewBox, name).toBe("0 0 40 40");
    expect(icon.shapes.length, name).toBeGreaterThan(1);
    expect(icon.shapes.some(([, attributes]) => attributes.class === "fill"), `${name}: a shape in the accent`).toBe(true);
  }
  // Lucide's forty, on Lucide's 24 grid, outlines only, as Lucide draws them.
  const lucide = ICON_NAMES.filter((name) => !(SITE_OWN_ICONS as readonly string[]).includes(name));
  expect(lucide).toHaveLength(40);
  for (const name of lucide) {
    const icon = icons[name]!;
    expect(icon.viewBox, name).toBe("0 0 24 24");
    expect(icon.shapes.length, name).toBeGreaterThan(0);
    expect(icon.shapes.some(([, attributes]) => "class" in attributes), `${name}: no shape of its own colour`).toBe(false);
  }
  // The comments of the file are not part of any icon.
  expect(JSON.stringify(icons)).not.toContain("drawing language");
});

test("Lucide's licence stands beside the sprite", () => {
  const licence = join(schemaDir, "LICENSE-Lucide.txt");
  expect(existsSync(licence)).toBe(true);
  expect(readFileSync(licence, "utf8")).toMatch(/^ISC License\n\nCopyright \(c\) for portions of Lucide/);
  expect(real).toContain("lucide-static 0.460.0");
});

test("the module the bundle imports is the sprite as data, and no markup", () => {
  const source = siteIconsSource(real);
  expect(source).toMatch(/^\/\/ Generated by builder\/build\/site-icons\.ts/);
  expect(source).not.toMatch(/<(svg|symbol|path)/);
  const data = JSON.parse(source.slice(source.indexOf("=") + 1).trim().replace(/;$/, "")) as Record<string, unknown>;
  expect(data).toEqual(readIcons(real));
});

// One fault each, in a copy of the real file.
const plants: Array<[string, string, RegExp]> = [
  ["a root other than <svg>", real.replace(/^<svg /, "<g ").replace(/<\/svg>\s*$/, "</g>"), /the root is <g>, not <svg>/],
  ["an element at the top that is no <symbol>", real.replace("</svg>", '<path d="M0 0"/></svg>'), /<path> at the top/],
  ["a symbol attribute other than id and viewBox", real.replace('<symbol id="info" viewBox', '<symbol id="info" onload="x()" viewBox'), /info: the symbol has attributes onload/],
  ["a <script> in a symbol", real.replace('<symbol id="info" viewBox="0 0 40 40">', '<symbol id="info" viewBox="0 0 40 40"><script>x()</script>'), /info: <script> is not a plain shape/],
  ["a <use> pointing elsewhere", real.replace('<symbol id="info" viewBox="0 0 40 40">', '<symbol id="info" viewBox="0 0 40 40"><use href="#x"/>'), /info: <use> is not a plain shape/],
  ["a shape holding an element", real.replace('<path d="M20 18v8"/>', '<path d="M20 18v8"><title>t</title></path>'), /info: <path> holds other elements/],
  ["a style attribute", real.replace('<path d="M20 18v8"/>', '<path style="fill:red" d="M20 18v8"/>'), /info: attribute style is not geometry/],
  ["an event handler", real.replace('<path d="M20 18v8"/>', '<path onclick="x()" d="M20 18v8"/>'), /info: attribute onclick is not geometry/],
  ["a class the page does not style", real.replace('<circle class="fill" cx="20" cy="20" r="12"/>', '<circle class="glow" cx="20" cy="20" r="12"/>'), /info: class glow is not one the page styles/],
];

describe("a fault planted in the sprite stops the build", () => {
  test.each(plants)("%s", (_name, text, message) => {
    expect(text).not.toBe(real);
    expect(() => readIcons(text)).toThrow(message);
  });
});
