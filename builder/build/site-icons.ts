// The icons an icon box may name, read from schema/icons.svg when the editor
// is built and served as `virtual:site-icons`. The server reads the same
// file (cms/app/models/site_icons.rb) and draws each icon inline on the
// published page, rebuilt element by element; the editor's renderer does
// the same from this module, so both draw the one file and neither carries
// its markup as a trusted string.
//
// The rules are the server's, so a file one side accepts the other does too:
// the root is <svg>; at the top only <symbol>, with no attribute but id and
// viewBox; inside a symbol only plain shapes (path, circle, ellipse, rect,
// line, polyline, polygon), holding no other element, with geometry
// attributes only, and a class only if it is one the page styles ("fill").
// Anything else stops the build, as it makes the server's loading raise.
// Comments and the text between elements are skipped, as Nokogiri's
// element_children skips them.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseFragment } from "parse5";
import type { Plugin } from "vite";
import { schemaDir } from "./paths.ts";

export const SITE_ICONS_MODULE = "virtual:site-icons";
const RESOLVED = `\0${SITE_ICONS_MODULE}`;
export const iconsFile = join(schemaDir, "icons.svg");

// cms/app/models/site_icons.rb's lists, word for word.
const ELEMENTS = ["path", "circle", "ellipse", "rect", "line", "polyline", "polygon"];
const ATTRIBUTES = ["d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points", "class"];
const CLASSES = ["fill"];

export type Shape = [element: string, attributes: Record<string, string>];
export interface SiteIcon {
  // null when the symbol has none, and the drawn <svg> then has none either.
  viewBox: string | null;
  shapes: Shape[];
}

interface Parse5Node {
  nodeName: string;
  tagName?: string;
  attrs?: Array<{ name: string; value: string }>;
  childNodes?: Parse5Node[];
}

const elementsOf = (node: Parse5Node): Parse5Node[] => (node.childNodes ?? []).filter((child) => child.tagName !== undefined);
const attributesOf = (node: Parse5Node): Array<{ name: string; value: string }> => node.attrs ?? [];

// The icons of a sprite, by symbol id, each with its viewBox and its shapes
// in document order. Throws on anything the server would refuse.
export function readIcons(text: string): Record<string, SiteIcon> {
  const roots = elementsOf(parseFragment(text) as Parse5Node);
  const root = roots[0];
  if (roots.length !== 1 || root?.tagName !== "svg") throw new Error(`site icons: the root is <${root?.tagName ?? "nothing"}>, not <svg>`);

  const icons: Record<string, SiteIcon> = {};
  for (const symbol of elementsOf(root)) {
    if (symbol.tagName !== "symbol") throw new Error(`site icons: <${symbol.tagName}> at the top: only <symbol> belongs there`);
    const symbolAttributes = attributesOf(symbol);
    const id = symbolAttributes.find((a) => a.name === "id")?.value;
    const extra = symbolAttributes.map((a) => a.name).filter((name) => name !== "id" && name !== "viewBox");
    if (extra.length > 0) throw new Error(`site icons: ${id}: the symbol has attributes ${extra.join(", ")}`);
    if (id === undefined) throw new Error("site icons: a symbol has no id");

    const shapes = elementsOf(symbol).map((shape): Shape => {
      const name = shape.tagName ?? "";
      if (!ELEMENTS.includes(name)) throw new Error(`site icons: ${id}: <${name}> is not a plain shape`);
      if (elementsOf(shape).length > 0) throw new Error(`site icons: ${id}: <${name}> holds other elements`);
      const attributes: Record<string, string> = {};
      for (const { name: attribute, value } of attributesOf(shape)) {
        if (!ATTRIBUTES.includes(attribute)) throw new Error(`site icons: ${id}: attribute ${attribute} is not geometry`);
        if (attribute === "class" && !CLASSES.includes(value)) throw new Error(`site icons: ${id}: class ${value} is not one the page styles`);
        attributes[attribute] = value;
      }
      return [name, attributes];
    });
    icons[id] = { viewBox: symbolAttributes.find((a) => a.name === "viewBox")?.value ?? null, shapes };
  }
  return icons;
}

export function siteIconsSource(text: string = readFileSync(iconsFile, "utf8")): string {
  return `// Generated by builder/build/site-icons.ts from schema/icons.svg.\nexport const SITE_ICONS = ${JSON.stringify(readIcons(text))};\n`;
}

// `import { SITE_ICONS } from "virtual:site-icons"`, read again from the
// file whenever the module is loaded, so it is never older than the file.
export function siteIcons(): Plugin {
  return {
    name: "page-builder-cms:site-icons",
    resolveId(source) {
      return source === SITE_ICONS_MODULE ? RESOLVED : null;
    },
    load(id) {
      if (id !== RESOLVED) return null;
      this.addWatchFile(iconsFile);
      return siteIconsSource();
    },
  };
}
