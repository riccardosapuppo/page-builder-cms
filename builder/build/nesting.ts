// The nesting rule, read from the schema: which block types the page and
// each block type may hold. The editor's drag and drop, paste and insert
// take their destinations from this table, so the rule exists once, in the
// schema, and is never written out again by hand. The schema's own lint
// (schema/tools/lint.ts) holds the schema to page > section > column >
// widget; this reads whatever the schema says.
//
// Counts (a section holds one to four columns, a column fifty widgets) are
// not read here: the editor checks them by validating the parent that
// would receive the block (src/document/check.ts), so they too stay in the
// schema alone.
type Node = Record<string, unknown>;

export const PAGE = "page";

function isNode(value: unknown): value is Node {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

// Reads the schema and returns { page: [...], <blockType>: [...] }, every
// list in the schema's order. Throws on anything it cannot read, so a schema
// that moved on fails the build instead of giving an empty rule.
export function nestingFromSchema(schema: unknown): Record<string, string[]> {
  if (!isNode(schema) || !isNode(schema.$defs)) throw new Error("nesting: the schema has no $defs");
  const defs = schema.$defs;
  const def = (name: string): Node => {
    const found = defs[name];
    if (!isNode(found)) throw new Error(`nesting: the schema has no $defs/${name}`);
    return found;
  };
  const deref = (node: Node): Node => {
    const ref = node.$ref;
    if (ref === undefined) return node;
    if (typeof ref !== "string" || !ref.startsWith("#/$defs/")) throw new Error(`nesting: cannot follow $ref ${String(ref)}`);
    return def(ref.slice("#/$defs/".length));
  };
  const enumOf = (node: Node, where: string): string[] => {
    const values = deref(node).enum;
    if (!Array.isArray(values) || values.length === 0 || !values.every((v) => typeof v === "string")) {
      throw new Error(`nesting: ${where} names no list of block types`);
    }
    return values as string[];
  };
  const blockTypes = enumOf(def("blockType"), "$defs/blockType");

  // The types an array of blocks accepts: its items narrow `type` to a const
  // or to an enum, directly or through a $ref.
  const typesOfItems = (children: Node, where: string): string[] => {
    const items = children.items;
    if (!isNode(items) || items.$ref !== "#/$defs/block") throw new Error(`nesting: ${where} does not hold blocks`);
    const properties = items.properties;
    const type = isNode(properties) ? properties.type : undefined;
    if (!isNode(type)) throw new Error(`nesting: ${where} does not say which block types it holds`);
    const types = typeof type.const === "string" ? [type.const] : enumOf(type, where);
    for (const t of types) if (!blockTypes.includes(t)) throw new Error(`nesting: ${where} names ${t}, which is not a block type`);
    return types;
  };

  const sections = isNode(schema.properties) ? schema.properties.sections : undefined;
  if (!isNode(sections)) throw new Error("nesting: the page has no sections");
  const table: Record<string, string[]> = { [PAGE]: typesOfItems(sections, "the page's sections") };

  // The block dispatcher: one if/then branch per type, then the branch's
  // children. A widget's children are noChildren, an array that holds nothing.
  const branches = def("block").allOf;
  if (!Array.isArray(branches)) throw new Error("nesting: $defs/block has no branches");
  for (const type of blockTypes) {
    const matching = branches.filter((b) => isNode(b) && isNode(b.if) && isNode(b.if.properties)
      && isNode(b.if.properties.type) && b.if.properties.type.const === type);
    if (matching.length !== 1) throw new Error(`nesting: ${matching.length} branches of $defs/block for ${type}, not 1`);
    const then = (matching[0] as Node).then;
    if (!isNode(then)) throw new Error(`nesting: the ${type} branch has no then`);
    const branch = deref(then);
    const children = isNode(branch.properties) ? branch.properties.children : undefined;
    if (!isNode(children)) throw new Error(`nesting: ${type} says nothing about its children`);
    const resolved = deref(children);
    table[type] = resolved.maxItems === 0 ? [] : typesOfItems(resolved, `the children of ${type}`);
  }
  return table;
}

// The module the editor imports, `virtual:block-document-nesting`.
export function nestingSource(schema: unknown): string {
  return `// Generated by builder/build/nesting.ts from schema/block-document.schema.json.\nexport const CHILD_TYPES = ${JSON.stringify(nestingFromSchema(schema))};\n`;
}
